/** كل الأذكار مسطّحة مع فئتها — مفيدة للبحث والمفضلة. */
export type ZekrWithCategory = Zekr & { categoryId: string; categoryTitle: string };

export function getAllZekrFlat(): ZekrWithCategory[] {
  return categories.flatMap((category) =>
    category.items.map((item) => ({
      ...item,
      categoryId: category.id,
      categoryTitle: category.title,
    }))
  );
}

export function searchZekr(query: string): ZekrWithCategory[] {
  const trimmed = query.trim();
  if (!trimmed) return [];
  return getAllZekrFlat().filter(
    (z) =>
      z.text.includes(trimmed) || z.virtue.includes(trimmed) || z.categoryTitle.includes(trimmed)
  );
}

export function getZekrByIds(ids: string[]): ZekrWithCategory[] {
  const idSet = new Set(ids);
  return getAllZekrFlat().filter((z) => idSet.has(z.id));
}
